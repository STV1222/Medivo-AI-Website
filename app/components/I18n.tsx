const I18nContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: DictionaryKey) => string;
} | null>(null);

function getStoredLanguage(): Language {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem(STORAGE_KEY) === "zh-Hant" ? "zh-Hant" : "en";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");
  const canPersist = useRef(false);

  useEffect(() => {
    window.setTimeout(() => {
      canPersist.current = true;
      setLanguageState(getStoredLanguage());
    }, 0);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "zh-Hant" ? "zh-Hant" : "en";
    if (canPersist.current) {
      window.localStorage.setItem(STORAGE_KEY, language);
    }
  }, [language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    canPersist.current = true;
    setLanguageState(nextLanguage);
  }, []);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key: DictionaryKey) => translations[language][key],
  }), [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useLanguage() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

export function useT() {
  return useLanguage().t;
}

export function Trans({ k }: { k: DictionaryKey }) {
  const t = useT();
  return <>{t(k)}</>;
}
